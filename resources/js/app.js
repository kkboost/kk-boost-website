const supportedLanguages = Object.keys(translations);

const getInitialLanguage = () => {
    const queryLanguage = new URLSearchParams(window.location.search).get('lang');
    if (supportedLanguages.includes(queryLanguage)) return queryLanguage;

    const storedLanguage = window.localStorage.getItem('kat_mapping_language');
    return supportedLanguages.includes(storedLanguage) ? storedLanguage : 'en';
};

const updateWhatsappLinks = (language) => {
    const baseUrl = window.katMapping?.whatsappUrl;
    if (!baseUrl) return;

    const message = translations[language]?.whatsapp_message || translations.en.whatsapp_message;
    document.querySelectorAll('[data-whatsapp-link]').forEach((link) => {
        link.href = `${baseUrl}?text=${encodeURIComponent(message)}`;
    });
};

const applyLanguage = (language) => {
    const activeLanguage = supportedLanguages.includes(language) ? language : 'en';
    const dictionary = translations[activeLanguage];

    document.documentElement.lang = activeLanguage;
    document.documentElement.dir = activeLanguage === 'ar' ? 'rtl' : 'ltr';
    document.title = 'KAT MAPPING — REMAP TO WIN';

    document.querySelectorAll('[data-i18n]').forEach((element) => {
        const translation = dictionary[element.dataset.i18n];
        if (translation) element.textContent = translation;
    });

    document.querySelectorAll('[data-language]').forEach((button) => {
        const isActive = button.dataset.language === activeLanguage;
        button.classList.toggle('is-active', isActive);
        button.setAttribute('aria-pressed', String(isActive));
    });

    updateWhatsappLinks(activeLanguage);
    window.localStorage.setItem('kat_mapping_language', activeLanguage);
};

const setupLanguagePicker = () => {
    applyLanguage(getInitialLanguage());

    document.querySelectorAll('[data-language]').forEach((button) => {
        button.addEventListener('click', () => {
            const language = button.dataset.language || 'en';
            applyLanguage(language);

            const url = new URL(window.location.href);
            url.searchParams.set('lang', language);
            window.history.replaceState({}, '', url);
        });
    });
};

const setupNavigation = () => {
    const header = document.querySelector('[data-site-header]');
    const menuButton = document.querySelector('[data-menu-button]');
    const mobileNavigation = document.querySelector('[data-mobile-navigation]');

    const updateHeader = () => header?.classList.toggle('is-scrolled', window.scrollY > 24);
    window.addEventListener('scroll', updateHeader, { passive: true });
    updateHeader();

    menuButton?.addEventListener('click', () => {
        const isOpen = menuButton.getAttribute('aria-expanded') === 'true';
        menuButton.setAttribute('aria-expanded', String(!isOpen));
        if (mobileNavigation) mobileNavigation.hidden = isOpen;
    });

    mobileNavigation?.querySelectorAll('a').forEach((link) => {
        link.addEventListener('click', () => {
            mobileNavigation.hidden = true;
            menuButton?.setAttribute('aria-expanded', 'false');
        });
    });
};

const setupRevealAnimations = () => {
    const elements = document.querySelectorAll('[data-reveal]');

    if (!('IntersectionObserver' in window) || window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
        elements.forEach((element) => element.classList.add('is-visible'));
        return;
    }

    const observer = new IntersectionObserver((entries, currentObserver) => {
        entries.forEach((entry) => {
            if (entry.isIntersecting) {
                entry.target.classList.add('is-visible');
                currentObserver.unobserve(entry.target);
            }
        });
    }, { threshold: 0.1, rootMargin: '0px 0px -6% 0px' });

    elements.forEach((element) => observer.observe(element));
};

const setupLazyVideo = () => {
    const video = document.querySelector('[data-lazy-video]');
    if (!video || window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;

    const loadVideo = () => {
        const source = video.querySelector('source[data-src]');
        if (!source || source.src) return;

        source.src = source.dataset.src;
        video.load();
        video.play().catch(() => {});
    };

    if (!('IntersectionObserver' in window)) {
        loadVideo();
        return;
    }

    const observer = new IntersectionObserver((entries, currentObserver) => {
        if (entries.some((entry) => entry.isIntersecting)) {
            loadVideo();
            currentObserver.disconnect();
        }
    }, { rootMargin: '280px 0px' });

    observer.observe(video);
};

document.addEventListener('DOMContentLoaded', () => {
    setupLanguagePicker();
    setupNavigation();
    setupRevealAnimations();
    setupLazyVideo();
});
